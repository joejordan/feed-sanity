/**
 * The CSS behind each short name used in `S2F_` selectors. See `atoms.ts`.
 *
 * Facebook gives every single-declaration rule a generated class name and
 * changes those names often. The declarations change far less, so selectors
 * in this project name the declaration (`S2F_disp_flex`) and `Atoms` looks up
 * the class Facebook is using for it today.
 *
 * Names are lowercase letters, digits and underscores, at most ten characters.
 */
export interface AtomRule {
  /** The rule's only declaration, as `property:value`. */
  css: string;
  /** A pseudo-class the rule's selector ends with, such as `:focus`. */
  pseudo?: string;
  /** Regex source for what comes before the class in the selector. `ATOM` stands for any class. */
  prefix?: string;
  /** A media condition the rule sits inside. There the class appears twice: `.x.x`. */
  media?: string;
}

